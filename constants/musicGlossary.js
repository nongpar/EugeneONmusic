// 단어 정렬을 미리 — 긴 용어부터 매칭해야 부분 매칭 오류를 줄임
// (예: "소나티네"가 "소나타"보다 먼저 매칭되어야 함)
const TERMS_SORTED = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);

// ── 한국어 단어 경계 처리 ──
// "조성진"의 "조성", "단조롭다"의 "단조", "장조림"의 "장조" 같은 합성어/인물명에서
// 음악 용어 부분만 잘못 매칭되는 걸 방지. 매칭된 영역의 앞뒤 글자를 보고:
//   - 앞 글자가 한글이면 합성어/이름으로 간주해 거부
//   - 뒤 글자가 한글인데 조사·접미사 화이트리스트에 없으면 합성어로 간주해 거부

const HANGUL_CHAR = /[가-힣]/;

// 단일 글자 조사·접미사 (가장 흔한 것들)
const PARTICLES_1 = new Set([
  '을', '를', '이', '가', '은', '는', '의', '에', '와', '과',
  '도', '만', '야', '여', '라', '며', '서', '들',
]);

// 두 글자 조사·접미사
const PARTICLES_2 = new Set([
  '으로', '부터', '까지', '보다', '처럼', '같이', '마저', '조차',
  '에서', '한테', '께서', '으면', '으니', '으나', '도록', '에는', '에도',
  '이라', '이며', '이고', '이나', '이든', '이지', '이다', '입니',
]);

function isValidWordBoundary(text, start, end) {
  // 앞 글자: 한글이면 합성어/이름으로 보고 거부
  if (start > 0) {
    const prev = text[start - 1];
    if (HANGUL_CHAR.test(prev)) return false;
  }
  // 뒤 글자: 한글이면 조사인지 확인
  if (end < text.length) {
    const next1 = text[end];
    if (HANGUL_CHAR.test(next1)) {
      if (PARTICLES_1.has(next1)) return true;
      // 두 글자 조사 시도
      if (end + 1 < text.length) {
        const next2 = next1 + text[end + 1];
        if (PARTICLES_2.has(next2)) return true;
      }
      return false; // 한글인데 조사 화이트리스트에 없음 — 합성어/이름
    }
  }
  return true;
}

export function getDefinition(term) {
  return GLOSSARY[term] || null;
}

export function getAllTerms() {
  return TERMS_SORTED;
}

/**
 * 텍스트에서 용어 위치를 찾아 segment 배열을 반환.
 *
 * 반환: [{ type: 'plain'|'term', text, term?: string }]
 *
 * 동일 용어가 한 메시지에서 여러 번 나오면 각각 매칭됨.
 * 긴 용어부터 매칭하되, 매칭된 영역은 다시 매칭하지 않도록 인덱스로 추적.
 * 한국어 단어 경계 체크로 합성어·인물명 오탐 방지 (예: "조성진"의 "조성").
 */
export function tokenizeWithGlossary(text) {
  if (!text) return [];

  // 매칭 위치 수집: [{ start, end, term }]
  const matches = [];
  const taken = new Array(text.length).fill(false);

  for (const term of TERMS_SORTED) {
    let idx = 0;
    while (idx < text.length) {
      const found = text.indexOf(term, idx);
      if (found < 0) break;
      const end = found + term.length;
      // 이미 점령된 영역과 겹치는지 확인
      let overlap = false;
      for (let i = found; i < end; i++) {
        if (taken[i]) {
          overlap = true;
          break;
        }
      }
      // 단어 경계 체크 — 합성어/인물명 오탐 방지
      if (!overlap && isValidWordBoundary(text, found, end)) {
        matches.push({ start: found, end, term });
        for (let i = found; i < end; i++) taken[i] = true;
      }
      idx = end;
    }
  }

  if (matches.length === 0) return [{ type: 'plain', text }];

  matches.sort((a, b) => a.start - b.start);

  const segments = [];
  let cursor = 0;
  for (const m of matches) {
    if (m.start > cursor) {
      segments.push({ type: 'plain', text: text.slice(cursor, m.start) });
    }
    segments.push({ type: 'term', text: text.slice(m.start, m.end), term: m.term });
    cursor = m.end;
  }
  if (cursor < text.length) {
    segments.push({ type: 'plain', text: text.slice(cursor) });
  }
  return segments;
}
