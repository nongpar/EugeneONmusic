const DEFAULT_MOOD = '오늘의 결';

/**
 * 사용자 메시지에서 결을 감지.
 * 매칭 안 되면 default ("오늘의 결") 반환.
 */
export function detectMood(text) {
  if (!text) return DEFAULT_MOOD;
  const lower = text.toLowerCase();
  for (const { label, keywords } of MOOD_PATTERNS) {
    for (const kw of keywords) {
      if (lower.includes(kw)) return label;
    }
  }
  return DEFAULT_MOOD;
}
